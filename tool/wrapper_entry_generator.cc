#include <icpp.hpp>

namespace {

bool is_newer(const fs::path &file0, const fs::path &file1) {
  std::error_code ec;
  if (!fs::exists(file0, ec))
    return false;
  if (!fs::exists(file1, ec))
    return true;
  return fs::last_write_time(file0, ec) > fs::last_write_time(file1, ec);
}

} // namespace

int main(int argc, const char *argv[]) {
  if (argc != 2) {
    std::println("Usage: {} /path/to/output", argv[0]);
    return -1;
  }

  auto outdir = std::string_view{argv[1]};
  auto outfile = fs::path{outdir} / "WrapperEntryStub.cpp";
  if (is_newer(outfile, argv[0])) {
    std::println("{} is up to update.", outfile.string());
    return 0;
  }

  std::ofstream ofs(outfile);
  ofs << "// Auto-generated by AetherVM, DO NOT EDIT!\n\n";
  ofs << "AETHER_NAKED void wrapper_entry_stub() { AETHER_ASM(\n";
  for (int i = 0; i < 100000; ++i)
    ofs << "\tAETHER_STUB\n";
  ofs << "); }\n";
  return 0;
}
